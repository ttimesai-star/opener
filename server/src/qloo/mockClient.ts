const FICTIONAL_PLACES = [
  "The Copper Room (bar)", "Northside Vinyl (record store)", "Lumen Coffee Roasters",
  "Dockyard Taproom", "Atlas Ramen", "Midnight Records & Bar",
];
const FICTIONAL_BRANDS = ["Fieldnote Apparel", "Brightwave Audio", "Canvas & Co. Sneakers", "Northfield Oat Drink"];

// FNV-1a: stable across runs so tests and demos are reproducible.
export function hash(text: string): number {
  let h = 0x811c9dc5;
  for (const ch of text) {
    h ^= ch.codePointAt(0) ?? 0;
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

function seeded(seed: number): () => number {
  let s = seed || 1;
  return () => {
    s = (Math.imul(s, 1664525) + 1013904223) >>> 0;
    return s / 0x100000000;
  };
}

function pick<T>(list: readonly T[], rnd: () => number, n: number): T[] {
  const copy = [...list];
  const out: T[] = [];
  while (out.length < n && copy.length > 0) out.push(copy.splice(Math.floor(rnd() * copy.length), 1)[0] as T);
  return out;
}

// Rough city centres for the map in demo mode. Unknown cities fall back to
// London so the map always has something to show.
const CITY_CENTRES: Record<string, [number, number]> = {
  london: [51.5072, -0.1276], "new york": [40.7128, -74.006], berlin: [52.52, 13.405],
  paris: [48.8566, 2.3522], austin: [30.2672, -97.7431], chicago: [41.8781, -87.6298],
  "los angeles": [34.0522, -118.2437], toronto: [43.6532, -79.3832], warsaw: [52.2297, 21.0122],
  amsterdam: [52.3676, 4.9041], barcelona: [41.3874, 2.1686], nashville: [36.1627, -86.7816],
};

export function cityCentre(city: string): [number, number] {
  return CITY_CENTRES[city.trim().toLowerCase()] ?? [51.5072, -0.1276];
}

function envelope(operation: string, results: unknown, extra: Partial<QlooEnvelope> = {}): QlooEnvelope {
  const count = Array.isArray(results) ? results.length : 1;
  return {
    schema_version: "1.0-preview.1",
    operation,
    status: count > 0 ? "ok" : "empty",
    summary: `[mock] ${operation} returned ${count} synthetic result(s).`,
    results,
    result_count: count,
    warnings: ["Synthetic demo data generated by Opener's mock client; not Qloo data."],
    execution: { transport: "direct", transport_name: "opener-mock", correlation_id: `mock-${operation}`, duration_ms: 1 },
    provenance: { source: "opener-mock", endpoint: "mock", documentation: "server/src/qloo/mockClient.ts" },
    ...extra,
  };
}

function str(v: unknown, fallback = ""): string {
  return typeof v === "string" ? v : fallback;
}

function strList(v: unknown): string[] {
  return Array.isArray(v) ? v.filter((x): x is string => typeof x === "string") : [];
}

export class MockQlooClient implements QlooClient {
  readonly mode = "mock" as const;
  readonly calls: { tool: QlooToolName; args: Record<string, unknown> }[] = [];
  // Optional simulated latency (MOCK_LATENCY_MS) so the streamed agent log can be
  // seen in demo mode; 0 in tests and CI.
  private readonly latencyMs: number;

  constructor(opts: { latencyMs?: number } = {}) {
    this.latencyMs = Math.max(0, Math.min(opts.latencyMs ?? 0, 5000));
  }

  async call(tool: QlooToolName, args: Record<string, unknown>): Promise<QlooEnvelope> {
    this.calls.push({ tool, args });
    if (this.latencyMs > 0) await new Promise((r) => setTimeout(r, this.latencyMs * (0.6 + Math.random() * 0.8)));
    switch (tool) {
      case "qloo_describe": {
        const name = str(args.entity, "Unknown");
        return envelope("describe", [{ entity_id: `mock-${hash(name).toString(16)}`, name, type: `urn:entity:${str(args.type, "artist")}`, popularity: 0.97 }]);
      }
      case "qloo_recommend": {
        const signals = strList(args.signals);
        const target = str(args.target_type, "artist");
        const rnd = seeded(hash(`${signals.join("|")}|${target}|${str(args.signal_location)}|${str(args.filter_location)}`));
        const limit = Math.min(Number(args.limit ?? 10), 20);
        const pool = target === "place" ? FICTIONAL_PLACES : target === "brand" ? FICTIONAL_BRANDS : FICTIONAL_ARTISTS;
        const results = pick(pool, rnd, limit)
          .map((name) => ({
            entity_id: `mock-${hash(name).toString(16)}`,
            name,
            type: `urn:entity:${target}`,
            popularity: Number((0.4 + rnd() * 0.55).toFixed(3)),
            affinity: Number((0.55 + rnd() * 0.44).toFixed(3)),
            // Live results carry a short description; the brief screens members of the headliner with it.
            ...(target === "artist" ? { properties: { short_description: "Fictional act generated for the Opener demo." } } : {}),
          }))
          .sort((a, b) => b.affinity - a.affinity);
        // Same contract as the live direct Insights call: filter.popularity.max.
        const max = args.popularity_max;
        if (typeof max === "number") {
          const kept = results.filter((r) => r.popularity <= max);
          return envelope("recommend", kept, {
            summary: `[mock] recommend returned ${kept.length} synthetic result(s) with popularity at most ${max}.`,
            provenance: { source: "opener-mock", endpoint: "mock /v2/insights", documentation: "server/src/qloo/mockClient.ts", requests: [{ method: "GET", path: "/v2/insights", query: { "filter.type": "urn:entity:artist", "filter.popularity.max": String(max) } }] },
          });
        }
        return envelope("recommend", results);
      }
      case "qloo_rank": {
        const options = strList(args.options);
        const rnd = seeded(hash(`${options.join("|")}|${strList(args.signals).join("|")}|${str(args.signal_location)}`));
        const results = options
          .map((name) => ({ entity_id: `mock-${hash(name).toString(16)}`, name, type: "urn:entity:artist", affinity: Number((0.3 + rnd() * 0.69).toFixed(3)) }))
          .sort((a, b) => b.affinity - a.affinity);
        return envelope("rank", results);
      }
      case "qloo_where_popular": {
        const within = str(args.within, "London");
        const [lat, lng] = cityCentre(within);
        const rnd = seeded(hash(`${str(args.entity)}|${within}`));
        const limit = Math.min(Number(args.limit ?? 10), 20);
        const results = Array.from({ length: limit }, () => ({
          location: { latitude: Number((lat + (rnd() - 0.5) * 0.18).toFixed(5)), longitude: Number((lng + (rnd() - 0.5) * 0.28).toFixed(5)) },
          query: { affinity: Number(rnd().toFixed(3)), popularity: Number(rnd().toFixed(3)) },
        })).sort((a, b) => b.query.affinity - a.query.affinity);
        return envelope("where_popular", results, { interpretation: { within } });
      }
      case "qloo_audience_demographics": {
        const rnd = seeded(hash(str(args.entity)));
        const r = () => Number((rnd() * 0.8 - 0.4).toFixed(3));
        return envelope("audience_demographics", [
          {
            entity_id: `mock-${hash(str(args.entity)).toString(16)}`,
            query: {
              age: { "24_and_younger": r(), "25_to_29": r(), "30_to_34": r(), "35_to_44": r(), "45_to_54": r(), "55_and_older": r() },
              gender: { male: r(), female: r() },
            },
          },
        ]);
      }
      case "qloo_trends": {
        const entities = strList(args.entities);
        const start = new Date(str(args.start_date, "2026-07-01"));
        const series = entities.map((name) => {
          const rnd = seeded(hash(`trend|${name}`));
          const slope = (rnd() - 0.45) * 0.6;
          const points = Array.from({ length: 12 }, (_, i) => {
            const d = new Date(start.getTime() + i * 7 * 86400000);
            return { date: d.toISOString().slice(0, 10), population_percentile: Number(Math.min(1, Math.max(0, 0.5 + slope * (i / 11) + (rnd() - 0.5) * 0.05)).toFixed(3)) };
          });
          return { entity: { entity_id: `mock-${hash(name).toString(16)}`, name, type: "urn:entity:artist" }, points };
        });
        return envelope("trends", series);
      }
      case "qloo_entity_tags": {
        const rnd = seeded(hash(strList(args.entities).join("|")));
        const tags = ["indie pop", "dream pop", "festival", "late-night", "vinyl collector", "synthwave", "singer-songwriter"];
        // Live entity_tags mixes tag families; the mock does too, so the filter is exercised.
        const taste = pick(tags, rnd, 5).map((name) => ({ id: `urn:tag:genre:music:${name.replace(/\W+/g, "_")}`, name, type: "urn:tag:genre:music", affinity: Number(rnd().toFixed(3)) }));
        const noise = [{ id: "urn:tag:credit_card:place:mock_card", name: "Mock Card", type: "urn:tag:credit_card:place", affinity: 0.9 }];
        return envelope("entity_tags", [...noise, ...taste]);
      }
      case "qloo_compare_audiences": {
        const rnd = seeded(hash(`${strList(args.group_a).join("|")}>${strList(args.group_b).join("|")}`));
        return envelope("compare_audiences", ["indie pop", "festival", "vinyl collector"].map((name) => ({ name, a: { affinity: Number(rnd().toFixed(3)) }, b: { affinity: Number(rnd().toFixed(3)) } })));
      }
      case "qloo_find_tags": {
        const q = str(args.query, "music");
        return envelope("find_tags", [{ id: `urn:tag:mock:${q.replace(/\W+/g, "_")}`, name: q, type: "urn:tag:genre" }]);
      }
    }
  }

  async close(): Promise<void> {}
}
