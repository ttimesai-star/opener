// Deterministic mock of the `qloo mcp` tools. Used until the hackathon key
// arrives and in CI. Every name it returns is fictional and every number is
// synthetic: nothing here is Qloo data, and the UI labels it as such.
//
// The result shapes follow the harness normalizers (compactEntity, heatmap
// points, demographics, trending) as far as the public docs show them. Verify
// against live responses on day 1 and adjust normalize.ts, not the agent.

import type { QlooClient, QlooEnvelope, QlooToolName } from "./types.ts";

